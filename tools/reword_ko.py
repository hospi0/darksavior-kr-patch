def main():
    sys.stdout.reconfigure(encoding='utf-8')
    write = '--write' in sys.argv
    files = {p: N.rd(p) for p in sorted(glob.glob(os.path.join(ROOT, 'work', 'text', 'darksavior_*.tsv')))}
    hit = {a: 0 for a, _ in REWORD}; log = []
    for rows in files.values():
        for r in rows:
            k0 = r['번역']
            for a, b in REWORD:
                if a in r['번역']:
                    hit[a] += r['번역'].count(a); r['번역'] = r['번역'].replace(a, b)
            if r['번역'] != k0:
                log.append((r['ID'], k0, r['번역']))
    miss = [a for a, n in hit.items() if not n]
    print('바꾼 줄 %d · 못 찾은 항목 %d %s' % (len(log), len(miss), miss))
    syl = {ch for rows in files.values() for r in rows for ch in r['번역'] if '가' <= ch <= '힣'}
    print('한글 음절 %d (목표 875 이하)' % len(syl))
    with open(os.path.join(ROOT, 'work', 'text', 'reword_log.tsv'), 'w', encoding='utf-8') as fh:
        fh.write('ID\t전\t후\n')
        for x in log:
            fh.write('\t'.join(x) + '\n')
    if write:
        for p, rows in files.items():
            N.wr(p, rows)
        print('적용 완료')


if __name__ == '__main__':
    main()
