n = 0; hit = set()
for p in sorted(glob.glob(os.path.join(ROOT, 'work', 'text', 'darksavior_*.tsv'))):
    rows = N.rd(p); ch = False
    for r in rows:
        k = r['번역']
        for a, b in REP:
            if a in k:
                k = k.replace(a, b); hit.add(a)
        if k != r['번역']:
            r['번역'] = k; ch = True; n += 1
    if ch:
        N.wr(p, rows)
